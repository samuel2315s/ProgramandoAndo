package guia1;

public class Ejercicio27 {
    public static void main(String[] args) {

        int tamaño = 6;

        for (int i = 1; i <= tamaño; i++) {
            
            for (int j = 1; j <= tamaño; j++) {
                System.out.print("* ");
            }
            
            
            System.out.println();
        }
    }
}